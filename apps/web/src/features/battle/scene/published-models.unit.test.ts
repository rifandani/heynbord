import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

import { describe, expect, it } from "vitest";

import {
  compressionProblems,
  readModelGltf,
} from "../../../../../../scripts/model-gltf";

const ROOT = path.resolve(import.meta.dirname, "../../../../../..");
const MODELS = path.join(ROOT, "apps/web/public/models");

const modelFiles = (directory: string): readonly string[] =>
  readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        return modelFiles(full);
      }
      return entry.name.endsWith(".glb") ? [path.relative(MODELS, full)] : [];
    })
    .toSorted();

const files = modelFiles(MODELS);

interface SourceContract {
  readonly clips: readonly { readonly name: string }[];
}

const CONTRACT_DIRS = new Map([
  ["units", "unit-model"],
  ["heroes", "hero-model"],
]);

const contracts = (
  family: string
): Readonly<Record<string, SourceContract>> => {
  const directory = CONTRACT_DIRS.get(family);
  if (directory === undefined) {
    throw new Error(`Unknown model family: ${family}`);
  }
  // SAFETY: source-contracts.json is generated by the packers; each value is a ModelContract.
  return JSON.parse(
    readFileSync(
      path.join(ROOT, "scripts", directory, "source-contracts.json"),
      "utf-8"
    )
  ) as Readonly<Record<string, SourceContract>>;
};

describe("published 3D models", () => {
  it("publishes at least one model", () => {
    expect(files.length).toBeGreaterThan(0);
  });

  it.each(files)("%s stores compressed geometry", (file) => {
    const data = readFileSync(path.join(MODELS, file));
    const gltf = readModelGltf(data);
    expect(compressionProblems(gltf)).toEqual([]);
    // A published GLB embeds its images, and every image is KTX2.
    expect((gltf.images ?? []).every((image) => image.uri === undefined)).toBe(
      true
    );
    expect(
      (gltf.images ?? []).every((image) => image.mimeType === "image/ktx2")
    ).toBe(true);
    expect(
      (gltf.textures ?? []).every(
        (texture) => texture.extensions?.KHR_texture_basisu !== undefined
      )
    ).toBe(true);
  });

  it.each(files)("%s has a committed source contract", (file) => {
    const family = path.dirname(file);
    expect(family).toMatch(/^(?:units|heroes)$/u);
    expect(contracts(family)[path.basename(file)]).toBeDefined();
  });
});
