const byId = new Map<string, CardDefinition>(
  CARDS.map((card) => [card.id, card])
);

/** The card definition for an ID. Throws for an unknown ID: content is checked by tests. */
export const getCard = (cardId: string): CardDefinition => {
  const card = byId.get(cardId);
  if (!card) {
    throw new Error(`Unknown card: ${cardId}`);
  }
  return card;
};
