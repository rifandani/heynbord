/**
 * Compress and validate a Blender-exported Hero Model, preserving its rig and clips.
 *   bun hero-model:pack standard-standard
 *   bun hero-model:pack --all
 * Raw sources stay in art/heroes/raw. Only checked Meshopt output is published.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { meshopt } from "@gltf-transform/functions";
import { MeshoptDecoder, MeshoptEncoder } from "meshoptimizer";

import { modelContract } from "../apps/web/scripts/model-contract.ts";
import type { ModelContract } from "../apps/web/scripts/model-contract.ts";
import { checkHeroModel } from "./hero-model/model-check.ts";

const ROOT = path.join(import.meta.dirname, "..");
const RAW = path.join(ROOT, "apps/web/art/heroes/raw");
const OUTPUT = path.join(ROOT, "apps/web/public/models/heroes");

const assertModel = (data: Uint8Array, compressed: boolean) => {
  const report = checkHeroModel(data, compressed);
  if (report.problems.length > 0) {
    throw new Error(
      report.problems.map((problem) => `- ${problem}`).join("\n")
    );
  }
  return report;
};

const distance = (left: readonly number[], right: readonly number[]): number =>
  Math.hypot(
    (left[0] ?? 0) - (right[0] ?? 0),
    (left[1] ?? 0) - (right[1] ?? 0),
    (left[2] ?? 0) - (right[2] ?? 0)
  );

/** Compression must keep every clip, bone and bound of the raw export. */
const assertContract = (
  name: string,
  source: ModelContract,
  published: ModelContract
): void => {
  if (
    published.clips.length !== source.clips.length ||
    source.clips.some(
      (clip) =>
        !published.clips.some(
          (other) =>
            other.name === clip.name &&
            other.duration === clip.duration &&
            other.keyframes === clip.keyframes
        )
    )
  ) {
    throw new Error(`${name}: compression changed the animation contract`);
  }
  if (JSON.stringify(published.bones) !== JSON.stringify(source.bones)) {
    throw new Error(`${name}: compression changed the skeleton`);
  }
  if (
    distance(published.min, source.min) >= 0.001 ||
    distance(published.max, source.max) >= 0.001
  ) {
    throw new Error(`${name}: compression changed the model bounds`);
  }
};

const argument = process.argv.at(2);
if (
  !argument ||
  (argument !== "--all" && !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(argument))
) {
  throw new Error("Usage: bun hero-model:pack <model-name|--all>");
}
const names =
  argument === "--all"
    ? readdirSync(RAW)
        .filter((file) => file.endsWith(".glb"))
        .map((file) => file.slice(0, -4))
        .toSorted()
    : [argument];
await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready]);
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({
    "meshopt.encoder": MeshoptEncoder,
    "meshopt.decoder": MeshoptDecoder,
  });
mkdirSync(OUTPUT, { recursive: true });

const pack = async (
  name: string
): Promise<{
  readonly name: string;
  readonly contract: ModelContract;
  readonly rawBytes: number;
  readonly packedBytes: number;
}> => {
  const rawPath = path.join(RAW, `${name}.glb`);
  if (!existsSync(rawPath)) {
    throw new Error(
      `No raw model at ${rawPath}. Run scripts/hero-model/reference.py in Blender first.`
    );
  }
  const raw = readFileSync(rawPath);
  const report = assertModel(raw, false);
  const source = await modelContract(raw);
  const document = await io.readBinary(raw);
  await document.transform(
    meshopt({ encoder: MeshoptEncoder, level: "medium" })
  );
  const packed = await io.writeBinary(document);
  assertModel(packed, true);
  // Decode the exact published bytes; malformed compressed data must fail before publication.
  assertContract(name, source, await modelContract(packed));
  if (packed.byteLength >= raw.byteLength) {
    throw new Error(`${name}: compression did not reduce the file size`);
  }
  writeFileSync(path.join(OUTPUT, `${name}.glb`), packed);
  console.log(
    `${name}: ${raw.byteLength} -> ${packed.byteLength} bytes; ${report.triangles} triangles, ${report.bones} bones, ${source.clips.length} clips`
  );
  return {
    name,
    contract: source,
    rawBytes: raw.byteLength,
    packedBytes: packed.byteLength,
  };
};

const results = await Promise.all(names.map(pack));
const contractPath = path.join(
  ROOT,
  "scripts/hero-model/source-contracts.json"
);
// SAFETY: these records are generated by modelContract, not external input.
const previous = existsSync(contractPath)
  ? (JSON.parse(readFileSync(contractPath, "utf-8")) as Record<
      string,
      ModelContract
    >)
  : {};
writeFileSync(
  contractPath,
  `${JSON.stringify(
    Object.assign(
      previous,
      ...results.map(({ name, contract }) => ({
        [`${name}.glb`]: contract,
      }))
    )
  )}\n`
);
const rawBytes = results.reduce((total, result) => total + result.rawBytes, 0);
const packedBytes = results.reduce(
  (total, result) => total + result.packedBytes,
  0
);
console.log(
  `total: ${rawBytes} -> ${packedBytes} bytes (${((1 - packedBytes / rawBytes) * 100).toFixed(2)}% smaller)`
);
